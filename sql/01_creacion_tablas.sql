-- =============================================================================
--  Sistema de préstamos de la Biblioteca Universitaria · Laboratorio 01
--  Script 1 de 3: CREACIÓN DE TABLAS
--
--  Motor: PostgreSQL 13 o superior.
--  Ejecutar sobre una base de datos VACÍA (por ejemplo biblioteca_db recién creada):
--      psql -U postgres -d biblioteca_db -v ON_ERROR_STOP=1 -f sql/01_creacion_tablas.sql
--
--  Las tablas y columnas son exactamente las que usa la aplicación Django, así que
--  después de este script y del 02 la app funciona sin ejecutar «migrate».
--
--  Diseño (ver el MER y el MR):
--    · Especialización TOTAL y DISJUNTA de usuarios: todo usuario es exactamente un
--      lector o un bibliotecario. «usuario» es el supertipo (columna discriminadora
--      «tipo»); «lector» y «bibliotecario» son los subtipos. El lector se divide en
--      estudiante o docente («rol»).
--      Lo DISJUNTO lo garantiza la base: cada subtipo guarda su tipo fijo y su llave
--      foránea apunta al PAR (id, tipo) del usuario; así un usuario solo cabe en el
--      subtipo de su tipo. Lo TOTAL (que todo usuario tenga su subtipo) lo garantiza la
--      aplicación, que crea las dos filas en una transacción (consulta 12 del script 3).
--    · Solo los lectores piden préstamos y solo los bibliotecarios aprueban, registran
--      devoluciones y cobran multas: las llaves foráneas apuntan al subtipo correcto.
--    · La multa es una tabla propia (0 o 1 por devolución) que guarda la tarifa aplicada.
--    · Los días de retraso no se guardan: se calculan con las fechas (atributo derivado).
--
--  Convenciones: llave primaria «id» (o la del supertipo en los subtipos), llaves
--  foráneas «<entidad>_id». Nombres de restricciones: <tabla>_pkey, <tabla>_<columna>_key
--  (UNIQUE), <tabla>_<columna>_fkey (FOREIGN KEY); los CHECK tienen nombre descriptivo.
--  Las llaves foráneas son DEFERRABLE INITIALLY DEFERRED (se verifican al confirmar la
--  transacción), igual que las que crea Django. No se crean índices adicionales: las
--  llaves primarias y los UNIQUE ya tienen el suyo automáticamente.
--
--  Organización:
--    Parte A  Modelo de la biblioteca (usuarios, catálogo, préstamos, multas)
--    Parte B  Tablas internas de Django (permisos, sesiones, registro de migraciones)
-- =============================================================================

BEGIN;

-- Búsqueda sin tildes en el catálogo y en usuarios («garcia» encuentra «García»)
CREATE EXTENSION IF NOT EXISTS unaccent;


-- =============================================================================
--  PARTE A · MODELO DE LA BIBLIOTECA
-- =============================================================================

-- -----------------------------------------------------------------------------
--  Cuenta de acceso (tabla de Django): usuario, contraseña cifrada, nombres y correo.
--  Cada usuario de la biblioteca tiene exactamente una.
-- -----------------------------------------------------------------------------
CREATE TABLE auth_user (
    id            integer GENERATED BY DEFAULT AS IDENTITY,
    password      varchar(128) NOT NULL,                 -- hash pbkdf2, nunca el texto plano
    last_login    timestamptz,
    is_superuser  boolean      NOT NULL DEFAULT false,
    username      varchar(150) NOT NULL,
    first_name    varchar(150) NOT NULL DEFAULT '',
    last_name     varchar(150) NOT NULL DEFAULT '',
    email         varchar(254) NOT NULL DEFAULT '',
    is_staff      boolean      NOT NULL DEFAULT false,
    is_active     boolean      NOT NULL DEFAULT true,
    date_joined   timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT auth_user_pkey PRIMARY KEY (id),
    CONSTRAINT auth_user_username_key UNIQUE (username)
);

-- -----------------------------------------------------------------------------
--  USUARIO (supertipo): lo que comparten lectores y bibliotecarios.
--  «tipo» es el discriminador de la especialización. Un usuario bloqueado puede
--  entrar y ver el catálogo, pero no pedir libros.
-- -----------------------------------------------------------------------------
CREATE TABLE usuario (
    id                    bigint      GENERATED BY DEFAULT AS IDENTITY,
    codigo_universitario  varchar(20) NOT NULL,
    identificacion        varchar(20) NOT NULL,
    tipo                  varchar(20) NOT NULL,                       -- lector | bibliotecario
    estado                varchar(20) NOT NULL DEFAULT 'activo',
    telefono              varchar(20) NOT NULL DEFAULT '',            -- opcional (texto vacío)
    fecha_registro        timestamptz NOT NULL DEFAULT now(),
    user_id               integer     NOT NULL,
    CONSTRAINT usuario_pkey PRIMARY KEY (id),
    CONSTRAINT usuario_codigo_universitario_key UNIQUE (codigo_universitario),
    CONSTRAINT usuario_identificacion_key UNIQUE (identificacion),
    CONSTRAINT usuario_user_id_key UNIQUE (user_id),                  -- relación 1 a 1 con la cuenta
    CONSTRAINT usuario_id_tipo_key UNIQUE (id, tipo),                 -- lo referencian los subtipos
    CONSTRAINT usuario_tipo_valido CHECK (tipo IN ('lector', 'bibliotecario')),
    CONSTRAINT usuario_estado_valido CHECK (estado IN ('activo', 'bloqueado')),
    -- Al eliminar la cuenta de acceso se elimina también el usuario
    CONSTRAINT usuario_user_id_fkey
        FOREIGN KEY (user_id) REFERENCES auth_user (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED
);
COMMENT ON TABLE usuario IS 'Supertipo: datos comunes de lectores y bibliotecarios (especialización total y disjunta)';

-- -----------------------------------------------------------------------------
--  LECTOR (subtipo): usuario que pide préstamos. «rol» lo divide en estudiante o docente.
--  Su llave primaria es la del usuario: un lector ES un usuario (relación 1 a 1).
--  «tipo» vale siempre 'lector': la llave foránea compuesta (usuario_id, tipo) solo
--  acepta usuarios cuyo tipo sea 'lector'.
-- -----------------------------------------------------------------------------
CREATE TABLE lector (
    usuario_id  bigint       NOT NULL,
    tipo        varchar(20)  NOT NULL DEFAULT 'lector',
    rol         varchar(20)  NOT NULL DEFAULT 'estudiante',
    carrera     varchar(150) NOT NULL DEFAULT '',                    -- opcional (texto vacío)
    CONSTRAINT lector_pkey PRIMARY KEY (usuario_id),
    CONSTRAINT lector_tipo_fijo CHECK (tipo = 'lector'),
    CONSTRAINT lector_rol_valido CHECK (rol IN ('estudiante', 'docente')),
    CONSTRAINT lector_usuario_id_tipo_fkey
        FOREIGN KEY (usuario_id, tipo) REFERENCES usuario (id, tipo) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED
);
COMMENT ON TABLE lector IS 'Subtipo: estudiantes y docentes que solicitan préstamos';

-- -----------------------------------------------------------------------------
--  BIBLIOTECARIO (subtipo): aprueba préstamos, registra devoluciones y cobra multas.
--  Existe sobre todo por sus relaciones: las llaves foráneas de préstamo, devolución y
--  multa apuntan aquí, así un lector no puede aparecer como quien aprobó o cobró.
--  Su atributo propio, el turno, es opcional (no está en el enunciado).
--  «tipo» vale siempre 'bibliotecario' (ver lector).
-- -----------------------------------------------------------------------------
CREATE TABLE bibliotecario (
    usuario_id  bigint      NOT NULL,
    tipo        varchar(20) NOT NULL DEFAULT 'bibliotecario',
    turno       varchar(10) NOT NULL DEFAULT '',                     -- '', manana, tarde o noche
    CONSTRAINT bibliotecario_pkey PRIMARY KEY (usuario_id),
    CONSTRAINT bibliotecario_tipo_fijo CHECK (tipo = 'bibliotecario'),
    CONSTRAINT bibliotecario_turno_valido CHECK (turno IN ('', 'manana', 'tarde', 'noche')),
    CONSTRAINT bibliotecario_usuario_id_tipo_fkey
        FOREIGN KEY (usuario_id, tipo) REFERENCES usuario (id, tipo) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED
);
COMMENT ON TABLE bibliotecario IS 'Subtipo: personal de la biblioteca';

-- -----------------------------------------------------------------------------
--  Catálogo: categorías, autores y libros (títulos)
-- -----------------------------------------------------------------------------
CREATE TABLE categoria (
    id           bigint       GENERATED BY DEFAULT AS IDENTITY,
    nombre       varchar(100) NOT NULL,
    descripcion  text         NOT NULL DEFAULT '',
    CONSTRAINT categoria_pkey PRIMARY KEY (id),
    CONSTRAINT categoria_nombre_key UNIQUE (nombre)
);

CREATE TABLE autor (
    id         bigint       GENERATED BY DEFAULT AS IDENTITY,
    nombre     varchar(100) NOT NULL,
    apellido   varchar(100) NOT NULL,
    biografia  text         NOT NULL DEFAULT '',
    CONSTRAINT autor_pkey PRIMARY KEY (id)
);

CREATE TABLE libro (
    id                bigint       GENERATED BY DEFAULT AS IDENTITY,
    isbn              varchar(20)  NOT NULL,
    titulo            varchar(255) NOT NULL,
    editorial         varchar(150) NOT NULL,
    anio_publicacion  integer      NOT NULL,
    descripcion       text         NOT NULL DEFAULT '',
    portada           varchar(100),                         -- ruta de la imagen dentro de media/
    creado_en         timestamptz  NOT NULL DEFAULT now(),  -- fecha de ingreso al catálogo («Recién llegados»)
    categoria_id      bigint,                               -- una categoría por libro (opcional)
    CONSTRAINT libro_pkey PRIMARY KEY (id),
    CONSTRAINT libro_isbn_key UNIQUE (isbn),
    CONSTRAINT libro_anio_publicacion_check CHECK (anio_publicacion >= 0),  -- la agrega Django (entero positivo)
    CONSTRAINT libro_anio_publicacion_valido CHECK (anio_publicacion BETWEEN 1000 AND 2100),
    -- Si se borra una categoría, sus libros quedan sin categoría (no se pierden)
    CONSTRAINT libro_categoria_id_fkey
        FOREIGN KEY (categoria_id) REFERENCES categoria (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED
);
COMMENT ON TABLE libro IS 'Títulos del catálogo; cada copia física es un ejemplar';

-- Relación muchos a muchos: un libro tiene uno o varios autores y un autor, varios libros.
-- Tiene su propio «id» (así la crea Django) y el par (libro, autor) no se repite.
CREATE TABLE libro_autor (
    id        bigint GENERATED BY DEFAULT AS IDENTITY,
    libro_id  bigint NOT NULL,
    autor_id  bigint NOT NULL,
    CONSTRAINT libro_autor_pkey PRIMARY KEY (id),
    CONSTRAINT libro_autor_libro_id_autor_id_key UNIQUE (libro_id, autor_id),
    CONSTRAINT libro_autor_libro_id_fkey
        FOREIGN KEY (libro_id) REFERENCES libro (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT libro_autor_autor_id_fkey
        FOREIGN KEY (autor_id) REFERENCES autor (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED
);

-- -----------------------------------------------------------------------------
--  Ejemplar: copia física de un libro, con código de barras, ubicación y estado.
--  La ubicación va en dos columnas atómicas (primera forma normal): sala y estante.
-- -----------------------------------------------------------------------------
CREATE TABLE ejemplar (
    id                 bigint       GENERATED BY DEFAULT AS IDENTITY,
    codigo_barras      varchar(50)  NOT NULL,
    sala               varchar(30)  NOT NULL,
    estante            varchar(30)  NOT NULL,
    estado             varchar(20)  NOT NULL DEFAULT 'disponible',
    notas              text         NOT NULL DEFAULT '',
    fecha_adquisicion  date,
    libro_id           bigint       NOT NULL,
    CONSTRAINT ejemplar_pkey PRIMARY KEY (id),
    CONSTRAINT ejemplar_codigo_barras_key UNIQUE (codigo_barras),
    CONSTRAINT ejemplar_estado_valido CHECK (estado IN ('disponible', 'prestado', 'perdido', 'mantenimiento')),
    -- Borrar un libro borra sus ejemplares (si alguno tiene préstamos, la regla de prestamo lo impide)
    CONSTRAINT ejemplar_libro_id_fkey
        FOREIGN KEY (libro_id) REFERENCES libro (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED
);
COMMENT ON TABLE ejemplar IS 'Copias físicas: disponible, prestado, perdido o en mantenimiento';

-- -----------------------------------------------------------------------------
--  Tarifa de multa por día de retraso. Se guarda el historial: rige la activa más
--  reciente, y cada multa recuerda con cuál se calculó.
-- -----------------------------------------------------------------------------
CREATE TABLE tarifa_multa (
    id             bigint       GENERATED BY DEFAULT AS IDENTITY,
    valor_dia      numeric(8,2) NOT NULL,
    vigente_desde  date         NOT NULL DEFAULT CURRENT_DATE,
    activa         boolean      NOT NULL DEFAULT true,
    CONSTRAINT tarifa_multa_pkey PRIMARY KEY (id),
    CONSTRAINT tarifa_multa_positiva CHECK (valor_dia > 0)
);

-- -----------------------------------------------------------------------------
--  Préstamo: lector + ejemplar + fechas. Ciclo:
--  pendiente → activo → (vencido) → devuelto o perdido;  pendiente → rechazado
-- -----------------------------------------------------------------------------
CREATE TABLE prestamo (
    id                 bigint      GENERATED BY DEFAULT AS IDENTITY,
    fecha_solicitud    timestamptz NOT NULL DEFAULT now(),
    fecha_prestamo     date,                            -- se llena al aprobar
    fecha_vencimiento  date,                            -- se llena al aprobar
    estado             varchar(20) NOT NULL DEFAULT 'pendiente',
    observaciones      text        NOT NULL DEFAULT '', -- ampliaciones de plazo, rechazos automáticos
    lector_id          bigint      NOT NULL,            -- quien lo pide: solo un lector
    ejemplar_id        bigint      NOT NULL,
    aprobado_por_id    bigint,                          -- quien lo aprobó o rechazó: solo un bibliotecario
    CONSTRAINT prestamo_pkey PRIMARY KEY (id),
    CONSTRAINT prestamo_estado_valido
        CHECK (estado IN ('pendiente', 'activo', 'vencido', 'devuelto', 'rechazado', 'perdido')),
    CONSTRAINT prestamo_vencimiento_posterior
        CHECK (fecha_prestamo IS NULL OR fecha_vencimiento IS NULL OR fecha_vencimiento >= fecha_prestamo),
    CONSTRAINT prestamo_aprobado_con_fechas
        CHECK (estado IN ('pendiente', 'rechazado') OR (fecha_prestamo IS NOT NULL AND fecha_vencimiento IS NOT NULL)),
    -- El historial se protege: no se puede borrar un lector ni un ejemplar con préstamos
    CONSTRAINT prestamo_lector_id_fkey
        FOREIGN KEY (lector_id) REFERENCES lector (usuario_id) ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT prestamo_ejemplar_id_fkey
        FOREIGN KEY (ejemplar_id) REFERENCES ejemplar (id) ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED,
    -- Si se borra al bibliotecario que aprobó, el préstamo se conserva sin ese dato
    CONSTRAINT prestamo_aprobado_por_id_fkey
        FOREIGN KEY (aprobado_por_id) REFERENCES bibliotecario (usuario_id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED
);
COMMENT ON TABLE prestamo IS 'Solicitudes y préstamos; el bibliotecario aprueba, rechaza o registra la devolución';

-- -----------------------------------------------------------------------------
--  Devolución: cierra un préstamo (a lo sumo una por préstamo) con la observación
--  del estado del ejemplar. La pérdida también se registra aquí (observacion = perdido).
-- -----------------------------------------------------------------------------
CREATE TABLE devolucion (
    id                   bigint      GENERATED BY DEFAULT AS IDENTITY,
    fecha_devolucion     date        NOT NULL DEFAULT CURRENT_DATE,
    observacion          varchar(50) NOT NULL DEFAULT '',  -- '', bueno, danado, paginas_faltantes, otro, perdido
    detalle_observacion  text        NOT NULL DEFAULT '',
    creado_en            timestamptz NOT NULL DEFAULT now(),
    prestamo_id          bigint      NOT NULL,
    registrado_por_id    bigint,                           -- solo un bibliotecario
    CONSTRAINT devolucion_pkey PRIMARY KEY (id),
    CONSTRAINT devolucion_prestamo_id_key UNIQUE (prestamo_id),   -- relación 1 a 1 con el préstamo
    CONSTRAINT devolucion_prestamo_id_fkey
        FOREIGN KEY (prestamo_id) REFERENCES prestamo (id) ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT devolucion_registrado_por_id_fkey
        FOREIGN KEY (registrado_por_id) REFERENCES bibliotecario (usuario_id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED
);
COMMENT ON TABLE devolucion IS 'Cierre de un préstamo con la observación del ejemplar';

-- -----------------------------------------------------------------------------
--  Multa: existe solo si la devolución fue tardía (0 o 1 por devolución).
--  monto = días de retraso × valor_dia de la tarifa aplicada. Se guarda el monto
--  (no solo la tarifa) porque es lo que se cobró y no debe cambiar.
--  Pagada ⇔ tiene fecha de pago.
-- -----------------------------------------------------------------------------
CREATE TABLE multa (
    id              bigint        GENERATED BY DEFAULT AS IDENTITY,
    devolucion_id   bigint        NOT NULL,
    tarifa_id       bigint        NOT NULL,
    monto           numeric(10,2) NOT NULL,
    pagada          boolean       NOT NULL DEFAULT false,
    fecha_pago      date,
    cobrada_por_id  bigint,                                -- solo un bibliotecario
    CONSTRAINT multa_pkey PRIMARY KEY (id),
    CONSTRAINT multa_devolucion_id_key UNIQUE (devolucion_id),     -- a lo sumo una multa por devolución
    CONSTRAINT multa_monto_positivo CHECK (monto > 0),
    CONSTRAINT multa_pago_coherente
        CHECK ((fecha_pago IS NOT NULL AND pagada) OR (fecha_pago IS NULL AND NOT pagada)),
    -- No se borra una devolución ni una tarifa que tengan multas: son historial de cobros
    CONSTRAINT multa_devolucion_id_fkey
        FOREIGN KEY (devolucion_id) REFERENCES devolucion (id) ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT multa_tarifa_id_fkey
        FOREIGN KEY (tarifa_id) REFERENCES tarifa_multa (id) ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT multa_cobrada_por_id_fkey
        FOREIGN KEY (cobrada_por_id) REFERENCES bibliotecario (usuario_id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED
);
COMMENT ON TABLE multa IS 'Multas por retraso: monto, tarifa aplicada y pago';


